using System.Buffers.Binary;

namespace RomRecon.Code;

/// <summary>
/// Backward-LZ ("BLZ", a.k.a. code compression) decoder used for the Nintendo DS ARM9 static module and for overlays.
///
/// This is a bounds-checked C# port of the reference decoder in the ndspy library (ndspy/codeCompression.py,
/// GPL-3.0 - the same licence as RanseiLink). Footer layout (last 8 bytes of the compressed region):
///   u32 = (headerLength &lt;&lt; 24) | compressedLength   (compressedLength counts back from the end, includes the header)
///   u32 = extraSize                                      (decompressed size minus compressed size, minus headerLength)
/// Bytes before the compressed region are passed through unchanged (for ARM9: the first 0x4000 bytes).
/// Conformance is tested against vectors generated by ndspy itself (see BlzTests).
/// </summary>
public static class Blz
{
    private const long MaxOutput = 64L * 1024 * 1024;

    /// <summary>ndspy _detectAppendedData: returns the amount of data appended after the footer, or null if the data does not look compressed.</summary>
    public static int? DetectAppendedData(ReadOnlySpan<byte> data)
    {
        for (int appended = 0; appended < 0x20; appended += 4)
        {
            if (data.Length < 5 + appended || data.Length < 8 + appended) { return null; }
            uint word = BinaryPrimitives.ReadUInt32LittleEndian(data.Slice(data.Length - appended - 8, 4));
            int headerLen = (int)(word >> 24);
            uint compressedLen = word & 0xFFFFFF;
            if (headerLen < 8) { continue; }
            if (compressedLen > data.Length) { continue; }
            return appended;
        }
        return null;
    }

    /// <summary>
    /// Decompress. Throws <see cref="InvalidDataException"/> for anything that is not a well-formed BLZ stream; never reads or
    /// writes out of bounds.
    /// </summary>
    public static byte[] Decompress(ReadOnlySpan<byte> input)
    {
        int? maybeAppended = DetectAppendedData(input);
        if (maybeAppended is null) { throw new InvalidDataException("Data does not look BLZ-compressed (no plausible footer)."); }
        int appendedAmount = maybeAppended.Value;
        ReadOnlySpan<byte> appended = input[^appendedAmount..];
        ReadOnlySpan<byte> data = input[..^appendedAmount];

        if (data.Length >= 4 && data[^4..].SequenceEqual(stackalloc byte[] { 0, 0, 0, 0 }))
        {
            // ndspy: a trailing 0-word marks data that was stored uncompressed (returned without appended data)
            return data.ToArray();
        }

        uint word = BinaryPrimitives.ReadUInt32LittleEndian(data.Slice(data.Length - 8, 4));
        uint extraSize = BinaryPrimitives.ReadUInt32LittleEndian(data.Slice(data.Length - 4, 4));
        int headerLen = (int)(word >> 24);
        long compressedLen = word & 0xFFFFFF;

        if (data.Length < headerLen) { throw new InvalidDataException($"File is too small for its footer ({data.Length} < {headerLen})."); }
        if (compressedLen > data.Length) { throw new InvalidDataException("Compressed length does not fit in the input."); }
        foreach (byte b in data.Slice(data.Length - headerLen, headerLen - 8))
        {
            if (b != 0xFF) { throw new InvalidDataException("Footer padding is not entirely 0xFF."); }
        }

        long passthroughLen = data.Length - compressedLen;
        long compDataLen = compressedLen - headerLen;
        if (compDataLen < 0) { throw new InvalidDataException("Footer length exceeds compressed length."); }
        long outLen = data.Length + (long)extraSize - passthroughLen;
        if (outLen < 0 || outLen > MaxOutput) { throw new InvalidDataException($"Implausible decompressed size ({outLen})."); }

        ReadOnlySpan<byte> comp = data.Slice((int)passthroughLen, (int)compDataLen);
        var dec = new byte[outLen];
        long outPos = 0, read = 0;
        int flags = 0, mask = 1;

        while (outPos < outLen)
        {
            if (mask == 1)
            {
                if (read >= comp.Length) { throw new InvalidDataException("Not enough data to decompress."); }
                flags = comp[(int)(comp.Length - 1 - read)];
                read++;
                mask = 0x80;
            }
            else
            {
                mask >>= 1;
            }

            if ((flags & mask) != 0)
            {
                if (read + 2 > comp.Length) { throw new InvalidDataException("Not enough data to decompress (back-reference)."); }
                int b1 = comp[(int)(comp.Length - 1 - read)]; read++;
                int b2 = comp[(int)(comp.Length - 1 - read)]; read++;
                int length = (b1 >> 4) + 3;
                long disp = (((b1 & 0x0F) << 8) | b2) + 3;
                if (disp > outPos)
                {
                    if (outPos < 2) { throw new InvalidDataException("Back-reference before the start of the output."); }
                    disp = 2; // ndspy quirk, kept for bit-exact behaviour
                }
                long src = outPos - disp;
                for (int i = 0; i < length; i++)
                {
                    if (outPos >= outLen) { break; }
                    dec[outLen - 1 - outPos] = dec[outLen - 1 - src];
                    src++;
                    outPos++;
                }
            }
            else
            {
                if (read >= comp.Length) { throw new InvalidDataException("Not enough data to decompress (literal)."); }
                dec[outLen - 1 - outPos] = comp[(int)(comp.Length - 1 - read)];
                read++;
                outPos++;
            }
        }

        var result = new byte[passthroughLen + outLen + appendedAmount];
        data[..(int)passthroughLen].CopyTo(result);
        dec.CopyTo(result, passthroughLen);
        appended.CopyTo(result.AsSpan((int)(passthroughLen + outLen)));
        return result;
    }

    public static bool TryDecompress(ReadOnlySpan<byte> input, out byte[] output, out string? error)
    {
        try
        {
            output = Decompress(input);
            error = null;
            return true;
        }
        catch (InvalidDataException e)
        {
            output = [];
            error = e.Message;
            return false;
        }
    }
}
